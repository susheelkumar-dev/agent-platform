"""What a generator produces: files with an owner, so regeneration knows what it may overwrite."""

from __future__ import annotations

from dataclasses import dataclass

# generated  rewritten on every run; a manual edit is detected (lock file) and reported as a conflict
# developer  written once when missing, never touched again (hooks, display components)
# block      an existing file the generator changes only between its own markers (src/displays.ts)
OWNERS = ("generated", "developer", "block")

GENERATED_BANNER = "Generated by UI Forge from {source}. Do not edit: the next generation overwrites this file. Put code in the developer-owned files instead ({hint})."


@dataclass
class GeneratedFile:
    root: str          # app | api
    path: str          # relative to the root, '/' separated
    content: str
    owner: str = "generated"
    source: str = ""   # schema document it comes from
    note: str = ""

    @property
    def key(self) -> str:
        return f"{self.root}:{self.path}"


def _comment(text: str) -> str:
    return text.replace("*/", "*\\/")  # a glob such as src/modules/*/x must not close the comment


def ts_banner(source: str, hint: str = "*.hooks.ts and the display component") -> str:
    return "/*\n * " + _comment(GENERATED_BANNER.format(source=source, hint=hint)) + "\n */\n"


def js_banner(source: str, hint: str = "*.hooks.js") -> str:
    return "'use strict';\n/*\n * " + _comment(GENERATED_BANNER.format(source=source, hint=hint)) + "\n */\n"
